_cache: dict[str, str] = {}


def reload() -> None:
    """خواندن دوباره همه متن‌ها از دیتابیس (بعد از ویرایش)."""
    global _cache
    _cache = db.all_texts()


def T(key: str, **kwargs) -> str:
    """متن کلید؛ با جایگذاری {placeholder}ها. اگر نبود، پیش‌فرض."""
    if key in _cache:
        raw = _cache[key]
    else:
        raw = db.get_text(key)
        if raw is None:
            raw = next((d for k, _, d in DEFAULTS if k == key), key)
        _cache[key] = raw
    if kwargs:
        try:
            return raw.format(**kwargs)
        except Exception:
            return raw
    return raw


def label_of(key: str) -> str:
    return next((label for k, label, _ in DEFAULTS if k == key), key)


def all_keys() -> list[str]:
    return [k for k, _, _ in DEFAULTS]
